import { expect, test } from "@playwright/test";

test("owner saves model controls, missing keys stay unavailable, and channel panels work on mobile", async ({ page }, testInfo) => {
  const origin = "http://localhost:3000";
  await page.goto("/sign-in");
  await page.getByLabel("Mock identity").fill("ai-controls-" + Date.now().toString(36));
  await page.getByRole("button", { name: "Continue with Google" }).click();
  await expect(page).toHaveURL(origin + "/");
  const response = await page.request.post("/api/workspaces", { headers: { origin }, data: { name: "Model controls" } });
  expect(response.status()).toBe(201);
  const workspace = await response.json();
  const configPath = `/api/workspaces/${workspace.id}/ai/config`;
  await page.goto(`/workspaces/${workspace.id}`);
  await expect(page.getByRole("heading", { name: "AI agents and models" })).toBeVisible();
  await page.getByLabel("Workspace default model", { exact: true }).selectOption("groq:openai/gpt-oss-20b");
  await page.getByLabel("Muse model", { exact: true }).selectOption("groq:openai/gpt-oss-20b");
  await page.getByLabel("Requests per member per hour").fill("2");
  await page.getByLabel("Requests per workspace per day").fill("4");
  await page.getByRole("button", { name: "Save agent settings" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Saved" })).toBeVisible();
  expect(await (await page.request.get(configPath)).json()).toMatchObject({ defaultModel: "groq:openai/gpt-oss-20b", museModel: "groq:openai/gpt-oss-20b", userHourlyLimit: 2, workspaceDailyLimit: 4, allowPaid: false });
  await page.reload();
  await expect(page.getByLabel("Muse model", { exact: true })).toHaveValue("groq:openai/gpt-oss-20b");
  await page.getByRole("button", { name: "Check available models" }).click();
  await expect(page.getByText("GEMINI_API_KEY is not configured.", { exact: true })).toBeVisible();
  await expect(page.getByText("GROQ_API_KEY is not configured.", { exact: true })).toBeVisible();
  const publicConfig = await (await page.request.get(`/api/workspaces/${workspace.id}/ai`)).json();
  expect(publicConfig.models).toEqual([]);
  expect(publicConfig.agents.find((agent: { id: string }) => agent.id === "muse").available).toBe(false);
  await page.goto(`/workspaces/${workspace.id}/channels/${workspace.channelId}`);
  await expect(page.getByText("Connected", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /ask agent/i }).click();
  await expect(page.getByLabel("AI agent", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Approved AI model").locator('option[value="groq:openai/gpt-oss-20b"]')).toBeDisabled();
  await expect(page.getByLabel("Workspace sidebar")).toBeVisible();
  await expect(page.getByLabel("Artifacts and activity", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByLabel("Message composer")).toBeVisible();
  const panels = page.getByRole("navigation", { name: "Workspace panels" });
  await panels.getByRole("button", { name: "Workspace", exact: true }).click();
  await expect(page.getByLabel("Workspace sidebar")).toBeVisible();
  await panels.getByRole("button", { name: "Artifacts & activity", exact: true }).click();
  await expect(page.getByLabel("Artifacts and activity", { exact: true })).toBeVisible();
  await panels.getByRole("button", { name: "Conversation", exact: true }).click();
  await expect(page.getByLabel("Message composer")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("mobile.png"), fullPage: true });
});
